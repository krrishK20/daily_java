import java.util.ArrayList;

public class Array_For_each{
    public static void main(String[] args){

        ArrayList<string> cars = new ArrayList<String>();
        cars.add("Volvo");
        cars.add("BMW");
        cars.add("Ford");
        cars.add("Mazda");

        for(String car : cars){
            System.out.println(car);
        }
    }
}